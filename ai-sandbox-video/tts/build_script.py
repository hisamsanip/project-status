"""Writes remotion/src/script.ts from lines.json + timings-<lang>.json (seconds of each line inside that language's voiceover).
If a language has no timings file yet, durations are ESTIMATED (flagged in the output) so the project still builds."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
L = json.load(open(HERE + "/lines.json"))
CLIP = {1: 9, 2: 8, 3: 11, 4: 10, 5: 11, 6: 10}   # length of each screen recording (capture/record.js)
OFFS = {"en": {"Intro": 0.0, "Outro": None}, "ms": {}}
def timings(lang):
    p = f"{HERE}/timings-{lang}.json"
    if os.path.exists(p): return json.load(open(p)), False
    t, out = 0.0, []
    for s in L[lang]["scenes"]:
        for l in s["lines"]:
            d = max(1.8, len(l["sub"]) * 0.072); out.append([round(t, 2), round(t + d, 2)]); t += d + 0.45
    return out, True
def f(x): return f"{x:.2f}"
def build(lang):
    tm, est = timings(lang); i = 0; scenes = []
    for s in L[lang]["scenes"]:
        durs = []
        for l in s["lines"]: durs.append(tm[i]); i += 1
        if s.get("kind") == "hyperframes":
            f0 = 0.6; d0 = durs[0][1] - durs[0][0]; f1 = f0 + d0 + 0.5
            scenes.append(dict(s=s, secs=s["seconds"], froms=[f0, f1], durs=durs))
        else:
            f0 = 0.3; d0 = durs[0][1] - durs[0][0]; f1 = f0 + d0 + 0.45; d1 = durs[1][1] - durs[1][0]
            scenes.append(dict(s=s, secs=round(max(CLIP[s["step"]], f1 + d1 + 0.8), 2), froms=[f0, f1], durs=durs))
    return scenes, est
def emit(lang, scenes, est):
    meta = L[lang]
    # HyperFrames film layout: EN intro, EN outro, MS intro, MS outro (see hyperframes/index.html)
    intro_en = L["en"]["scenes"][0]["seconds"]; outro_en = L["en"]["scenes"][-1]["seconds"]; intro_ms = L["ms"]["scenes"][0]["seconds"]
    trim = {"en": {"Intro": 0.0, "Outro": intro_en}, "ms": {"Intro": intro_en + outro_en, "Outro": intro_en + outro_en + intro_ms}}[lang]
    o = [f"  {lang}: {{", f'    voiceover: "{meta["voiceover"]}",', f'    voiceName: "{meta["voice"]}",' + ("  // ESTIMATED timings until the voiceover is generated" if est else ""), "    scenes: ["]
    for sc in scenes:
        s = sc["s"]; lines = ",\n".join(
            f'          {{ from: {f(fr)}, text: {json.dumps(l["sub"], ensure_ascii=False)}, audio: [{f(d[0])}, {f(d[1])}] }}'
            for l, fr, d in zip(s["lines"], sc["froms"], sc["durs"]))
        if s.get("kind") == "hyperframes":
            o.append(f'      {{\n        id: "{s["id"]}", kind: "hyperframes", seconds: {sc["secs"]}, trimBeforeSeconds: {trim[s["id"]]},\n        lines: [\n{lines},\n        ],\n      }},')
        else:
            o.append(f'      step({s["step"]}, {sc["secs"]}, {json.dumps(s["title"], ensure_ascii=False)}, [\n{lines},\n      ]),')
    o += ["    ],", "  },"]
    return "\n".join(o)
head = '''// The whole video in one place, per language: scene order, timing, footage, voiceover and
// subtitle lines. Times are in seconds, relative to the start of each scene.
// GENERATED by tts/build_script.py from tts/lines.json and the voiceover timings. Edit lines.json, not this file.

export const FPS = 30;

// `audio` is the [start, end] of this line inside the language's voiceover file.
export type Line = { from: number; text: string; audio: [number, number] };
export const lineEnd = (l: Line) => l.from + (l.audio[1] - l.audio[0]);

export type Scene =
  | { id: string; kind: "hyperframes"; seconds: number; trimBeforeSeconds: number; lines: Line[] }
  | { id: string; kind: "step"; seconds: number; step: number; title: string; clip: string; clipSeconds: number; lines: Line[] };

export type Lang = "en" | "ms";
export type Script = { voiceover: string; voiceName: string; scenes: Scene[] };

// The six screen recordings are shared by both languages. When a language needs a scene
// longer than its recording, the last frame is held.
const CLIP_SECONDS = { step1: 9, step2: 8, step3: 11, step4: 10, step5: 11, step6: 10 };
const step = (n: 1 | 2 | 3 | 4 | 5 | 6, seconds: number, title: string, lines: Line[]): Scene => ({
  id: `Step${n}`, kind: "step", seconds, step: n, title, clip: `clips/step${n}.mp4`, clipSeconds: CLIP_SECONDS[`step${n}`], lines,
});

export const SCRIPTS: Record<Lang, Script> = {
'''
tail = '''};

export const sceneFrames = (s: Scene) => Math.round(s.seconds * FPS);
export const totalFrames = (lang: Lang) => SCRIPTS[lang].scenes.reduce((n, s) => n + sceneFrames(s), 0);
'''
parts = []; info = {}
for lang in ("en", "ms"):
    sc, est = build(lang); parts.append(emit(lang, sc, est)); info[lang] = (round(sum(x["secs"] for x in sc), 1), "estimated" if est else "from voiceover")
open(HERE + "/../remotion/src/script.ts", "w").write(head + "\n".join(parts) + "\n" + tail)
print(info)
